import { Chess } from 'chess.js';
import { OpeningEntry } from '../types/chess';

interface RawOpeningInput {
  id: string;
  eco: string;
  name: string;
  variation?: string;
  category: OpeningEntry['category'];
  styleTags: OpeningEntry['styleTags'];
  moves: string[];
  description: string;
  whitePlans: string[];
  blackPlans: string[];
  commonMistakes: string[];
  tacticalIdeas: string[];
}

function buildOpening(raw: RawOpeningInput): OpeningEntry {
  const c = new Chess();
  const validMoves: string[] = [];
  for (const san of raw.moves) {
    try {
      const m = c.move(san);
      if (m) validMoves.push(m.san);
    } catch {
      break;
    }
  }
  return {
    ...raw,
    moves: validMoves,
    pgn: c.pgn(),
    fen: c.fen(),
  };
}

